declare(strict_types=1);

namespace Iranimij\OpenImport\Model\Import\UrlRewrite;

use Iranimij\OpenImport\Model\Bridge\ImporterInterface;
use Iranimij\OpenImport\Model\Bridge\ImportRequest;
use Iranimij\OpenImport\Model\Bridge\ImportResult;
use Iranimij\OpenImport\Model\Bridge\RowError;
use Magento\ImportExport\Model\Import;
use Magento\ImportExport\Model\Import\AbstractSource;
use Psr\Log\LoggerInterface;

/**
 * URL rewrites by request path and store view: custom rewrites (any target, 301, 302 or a plain rewrite) and
 * rewrites of a product (by SKU), a category (by path) or a CMS page (by identifier), whose target is the entity's
 * current URL when a redirect is wanted, its canonical path otherwise. Add/Update creates or updates, Delete
 * removes, Replace is refused. Magento's own generated URLs are never changed or deleted: a request path that is
 * the generated URL of another entity is reported as a conflict.
 */
class UrlRewriteImporter implements ImporterInterface
{
    public const COLUMNS = ['request_path', 'store_code', 'target_path', 'redirect_type', 'entity_type',
        'product_sku', 'category_path', 'cms_page', 'description', 'autogenerated', 'metadata'];

    private const CANONICAL = [
        UrlRewriteRecords::PRODUCT => 'catalog/product/view/id/%d',
        UrlRewriteRecords::CATEGORY => 'catalog/category/view/id/%d',
        UrlRewriteRecords::CMS_PAGE => 'cms/page/view/page_id/%d',
    ];

    /**
     * @param UrlRewriteRecords $records
     * @param LoggerInterface $logger
     */
    public function __construct(
        private readonly UrlRewriteRecords $records,
        private readonly LoggerInterface $logger
    ) {
    }

    /**
     * @inheritDoc
     */
    public function run(ImportRequest $request, AbstractSource $source): ImportResult
    {
        $started = microtime(true);
        $errors = [];
        $ready = [];
        $position = 0;
        if ($request->behavior === Import::BEHAVIOR_REPLACE) {
            $errors[] = new RowError(
                null,
                'behavior',
                'URL rewrites cannot be imported with "Replace". Use Add/Update or Delete.',
                null,
                true
            );
        }
        $stores = $this->records->storeCodes();
        $seen = [];
        $created = $updated = $deleted = 0;
        foreach ($source as $row) {
            $prepared = $this->prepare($row, $stores, $request->behavior, $seen);
            if (isset($prepared['error'])) {
                [$column, $message] = $prepared['error'];
                $errors[] = new RowError($position, $column, $message, $column, true);
            } else {
                $ready[$position] = $prepared;
                $seen[$prepared['data']['store_id'] . '|' . $prepared['data']['request_path']] = true;
                if ($request->behavior === Import::BEHAVIOR_DELETE) {
                    $deleted++;
                } elseif ($prepared['existing'] === null) {
                    $created++;
                } else {
                    $updated++;
                }
            }
            $position++;
        }
        $invalid = count(array_filter($errors, static fn (RowError $error): bool => $error->row !== null));
        $valid = $errors === [] || ($request->skipErrors && $invalid <= $request->allowedErrors
            && !array_filter($errors, static fn (RowError $error): bool => $error->row === null));
        if ($request->dryRun || !$valid) {
            return $this->result($valid, false, $position, $invalid, $created, $updated, $deleted, $errors, $started);
        }
        $created = $updated = $deleted = 0;
        foreach ($ready as $index => $prepared) {
            try {
                if ($request->behavior === Import::BEHAVIOR_DELETE) {
                    $this->records->delete((int) $prepared['existing']['url_rewrite_id']);
                    $deleted++;
                } else {
                    $this->records->save($prepared['existing'], $prepared['data']);
                    $prepared['existing'] === null ? $created++ : $updated++;
                }
            } catch (\Throwable $exception) {
                $this->logger->error(
                    'OpenImport URL rewrite import: ' . $exception->getMessage(),
                    ['exception' => $exception]
                );
                $errors[] = new RowError($index, 'save', $exception->getMessage(), null, !$request->skipErrors);
                $invalid++;
                if (!$request->skipErrors) {
                    return $this->result(
                        false,
                        $created + $updated + $deleted > 0,
                        $position,
                        $invalid,
                        $created,
                        $updated,
                        $deleted,
                        $errors,
                        $started
                    );
                }
            }
        }

        return $this->result(true, true, $position, $invalid, $created, $updated, $deleted, $errors, $started);
    }

    /**
     * Turns a file row into url_rewrite data, or an error.
     *
     * @param array<string, mixed> $row
     * @param array<string, int> $stores
     * @param string $behavior
     * @param array<string, true> $seen store id|request path of the rows before
     * @return array{data?: array<string, mixed>, existing?: array<string, mixed>|null,
     *     error?: array{0: string, 1: string}}
     */
    private function prepare(array $row, array $stores, string $behavior, array $seen): array
    {
        $get = static fn (string $column): string => trim((string) ($row[$column] ?? ''));
        $requestPath = ltrim($get('request_path'), '/');
        if ($requestPath === '') {
            return ['error' => ['request_path', 'The request path is empty.']];
        }
        if (str_contains($requestPath, '//') || str_contains($requestPath, '#')
            || preg_match('/\s/', $requestPath) === 1 || preg_match('#^[a-z]+://#i', $requestPath) === 1) {
            return ['error' => ['request_path', sprintf(
                'The request path "%s" is not a path: no spaces, no "#", no "//", no scheme; e.g. old-shirts.html.',
                $requestPath
            )]];
        }
        $storeCode = strtolower($get('store_code'));
        if ($storeCode === '') {
            $storeId = $this->records->defaultStoreId();
        } elseif (isset($stores[$storeCode])) {
            $storeId = $stores[$storeCode];
        } else {
            return ['error' => ['store_code', sprintf(
                'There is no store view "%s" (store view codes: %s).',
                $get('store_code'),
                implode(', ', array_keys($stores))
            )]];
        }
        if (isset($seen[$storeId . '|' . $requestPath])) {
            return ['error' => ['request_path', sprintf(
                '"%s" appears twice in the file for this store view.',
                $requestPath
            )]];
        }
        $existing = $this->records->find($requestPath, $storeId);
        if ($behavior === Import::BEHAVIOR_DELETE) {
            if ($existing === null) {
                return ['error' => ['request_path', sprintf(
                    'There is no rewrite for "%s" in this store view.',
                    $requestPath
                )]];
            }
            if ((int) $existing['is_autogenerated'] === 1) {
                return ['error' => ['request_path', sprintf(
                    '"%s" is the URL Magento generated for %s; it cannot be deleted (it would come back).',
                    $requestPath,
                    $this->describe($existing)
                )]];
            }

            return ['data' => ['store_id' => $storeId, 'request_path' => $requestPath], 'existing' => $existing];
        }

        $redirect = match (strtolower($get('redirect_type'))) {
            '', '0', 'no', 'none', 'keine', 'rewrite' => 0,
            '301', 'permanent', 'dauerhaft' => 301,
            '302', 'temporary', 'temporär', 'temporaer' => 302,
            default => null,
        };
        if ($redirect === null) {
            return ['error' => ['redirect_type', sprintf(
                '"%s" is not a redirect type: use 0 (no redirect), 301 (permanent) or 302 (temporary).',
                $get('redirect_type')
            )]];
        }
        $entity = $this->entity($get, $storeId);
        if (isset($entity['error'])) {
            return ['error' => $entity['error']];
        }
        $targetPath = ltrim($get('target_path'), '/');
        if ($targetPath === '' && $entity['type'] !== UrlRewriteRecords::CUSTOM) {
            $targetPath = $redirect !== 0
                ? ($this->records->systemPath($entity['type'], $entity['id'], $storeId)
                    ?? sprintf(self::CANONICAL[$entity['type']], $entity['id']))
                : sprintf(self::CANONICAL[$entity['type']], $entity['id']);
        }
        if ($targetPath === '') {
            return ['error' => ['target_path',
                'A custom rewrite needs a target path (or name a product, category or CMS page).']];
        }
        if (strcasecmp($targetPath, $requestPath) === 0) {
            return ['error' => ['target_path', sprintf('"%s" points to itself.', $requestPath)]];
        }
        if ($existing !== null && (int) $existing['is_autogenerated'] === 1
            && ((string) $existing['entity_type'] !== $entity['type']
                || (int) $existing['entity_id'] !== $entity['id'])) {
            return ['error' => ['request_path', sprintf(
                '"%s" is the URL Magento generated for %s; it cannot be changed. Choose another request path.',
                $requestPath,
                $this->describe($existing)
            )]];
        }
        $metadata = $get('metadata');
        if ($metadata !== '' && json_decode($metadata, true) === null) {
            return ['error' => ['metadata', 'The metadata is not JSON.']];
        }
        $autogenerated = $get('autogenerated');

        return [
            'data' => [
                'store_id' => $storeId,
                'request_path' => $requestPath,
                'target_path' => $targetPath,
                'redirect_type' => $redirect,
                'entity_type' => $entity['type'],
                'entity_id' => $entity['id'],
                'description' => $get('description') !== '' ? $get('description') : null,
                'is_autogenerated' => in_array(strtolower($autogenerated), ['1', 'yes', 'true'], true) ? 1 : 0,
                'metadata' => $metadata !== '' ? $metadata : null,
            ],
            'existing' => $existing,
        ];
    }

    /**
     * The entity a row names: by the filled column, checked against an explicit entity_type.
     *
     * @param callable(string): string $get
     * @param int $storeId
     * @return array{type: string, id: int}|array{error: array{0: string, 1: string}}
     */
    private function entity(callable $get, int $storeId): array
    {
        $type = strtolower(str_replace(['_', ' '], '-', $get('entity_type')));
        $type = $type === 'cms' || $type === 'page' ? UrlRewriteRecords::CMS_PAGE : $type;
        $named = [];
        if ($get('product_sku') !== '') {
            $named[UrlRewriteRecords::PRODUCT] = 'product_sku';
        }
        if ($get('category_path') !== '') {
            $named[UrlRewriteRecords::CATEGORY] = 'category_path';
        }
        if ($get('cms_page') !== '') {
            $named[UrlRewriteRecords::CMS_PAGE] = 'cms_page';
        }
        if (count($named) > 1) {
            return ['error' => ['entity_type', 'Name one of product_sku, category_path and cms_page, not several.']];
        }
        if ($type !== '' && $type !== UrlRewriteRecords::CUSTOM && !isset(self::CANONICAL[$type])) {
            return ['error' => ['entity_type', sprintf(
                '"%s" is not an entity type: use custom, product, category or cms-page.',
                $get('entity_type')
            )]];
        }
        if ($named === []) {
            if ($type !== '' && $type !== UrlRewriteRecords::CUSTOM) {
                return ['error' => ['entity_type', sprintf(
                    'A %s rewrite needs the %s column.',
                    $type,
                    ['product' => 'product_sku', 'category' => 'category_path', 'cms-page' => 'cms_page'][$type]
                )]];
            }

            return ['type' => UrlRewriteRecords::CUSTOM, 'id' => 0];
        }
        $kind = (string) array_key_first($named);
        if ($type !== '' && $type !== $kind) {
            return ['error' => ['entity_type',
                sprintf('The entity type is %s but %s is filled.', $type, $named[$kind])]];
        }
        $value = $get($named[$kind]);
        $id = match ($kind) {
            UrlRewriteRecords::PRODUCT => $this->records->productId($value),
            UrlRewriteRecords::CATEGORY => $this->records->categoryId($value),
            default => $this->records->cmsPageId($value, $storeId),
        };
        if ($id === null) {
            return ['error' => [$named[$kind], sprintf('There is no %s "%s".', str_replace('-', ' ', $kind), $value)]];
        }

        return ['type' => $kind, 'id' => $id];
    }

    /**
     * @param array<string, mixed> $rewrite a url_rewrite row
     * @return string "product SHIRT-1", "category Men/Shirts", "CMS page about", "a custom rewrite"
     */
    private function describe(array $rewrite): string
    {
        $id = (int) $rewrite['entity_id'];

        return match ((string) $rewrite['entity_type']) {
            UrlRewriteRecords::PRODUCT => 'product ' . ($this->records->sku($id) ?? '#' . $id),
            UrlRewriteRecords::CATEGORY => 'category ' . ($this->records->categoryPath($id) ?? '#' . $id),
            UrlRewriteRecords::CMS_PAGE => 'CMS page ' . ($this->records->cmsPageIdentifier($id) ?? '#' . $id),
            default => 'a custom rewrite',
        };
    }

    /**
     * @param bool $valid
     * @param bool $imported
     * @param int $rows
     * @param int $invalid
     * @param int $created
     * @param int $updated
     * @param int $deleted
     * @param RowError[] $errors
     * @param float $started
     * @return ImportResult
     */
    private function result(
        bool $valid,
        bool $imported,
        int $rows,
        int $invalid,
        int $created,
        int $updated,
        int $deleted,
        array $errors,
        float $started
    ): ImportResult {
        return new ImportResult(
            $valid,
            $imported,
            $rows,
            $rows,
            $invalid,
            $created,
            $updated,
            $deleted,
            $errors,
            null,
            microtime(true) - $started
        );
    }
}
