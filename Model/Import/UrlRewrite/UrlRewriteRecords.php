declare(strict_types=1);

namespace Iranimij\OpenImport\Model\Import\UrlRewrite;

use Iranimij\OpenImport\Model\Import\Category\CategoryTree;
use Iranimij\OpenImport\Model\Import\Cms\CmsRecords;
use Magento\Framework\App\ResourceConnection;
use Magento\Store\Model\StoreManagerInterface;
use Magento\UrlRewrite\Model\ResourceModel\UrlRewrite as UrlRewriteResource;
use Magento\UrlRewrite\Model\UrlRewrite;
use Magento\UrlRewrite\Model\UrlRewriteFactory;

/**
 * The shop's URL rewrites (`url_rewrite`) and what the import links them to: store views by code, products by
 * SKU, categories by path, CMS pages by identifier. Reads are plain selects; writes go through the URL rewrite
 * model and its resource, as the admin's URL rewrite form does.
 */
class UrlRewriteRecords
{
    public const CUSTOM = 'custom';
    public const PRODUCT = 'product';
    public const CATEGORY = 'category';
    public const CMS_PAGE = 'cms-page';

    /**
     * @var array<string, int>|null lower-cased SKU => product id
     */
    private ?array $products = null;

    /**
     * @var array<int, string>|null product id => SKU
     */
    private ?array $skus = null;

    /**
     * @param ResourceConnection $resource
     * @param StoreManagerInterface $storeManager
     * @param UrlRewriteFactory $rewriteFactory
     * @param UrlRewriteResource $rewriteResource
     * @param CategoryTree $categories
     * @param CmsRecords $cms
     */
    public function __construct(
        private readonly ResourceConnection $resource,
        private readonly StoreManagerInterface $storeManager,
        private readonly UrlRewriteFactory $rewriteFactory,
        private readonly UrlRewriteResource $rewriteResource,
        private readonly CategoryTree $categories,
        private readonly CmsRecords $cms
    ) {
    }

    /**
     * @return array<string, int> lower-cased store view code => id (store views only, no "all")
     */
    public function storeCodes(): array
    {
        $codes = [];
        foreach ($this->storeManager->getStores() as $store) {
            $codes[strtolower((string) $store->getCode())] = (int) $store->getId();
        }

        return $codes;
    }

    /**
     * @return int the default store view's id
     */
    public function defaultStoreId(): int
    {
        return (int) $this->storeManager->getDefaultStoreView()?->getId();
    }

    /**
     * @param int $storeId
     * @return string
     */
    public function storeCode(int $storeId): string
    {
        return $this->cms->storeCode($storeId);
    }

    /**
     * The rewrite that answers a request path in a store view.
     *
     * @param string $requestPath
     * @param int $storeId
     * @return array<string, mixed>|null the url_rewrite row
     */
    public function find(string $requestPath, int $storeId): ?array
    {
        $connection = $this->resource->getConnection();
        $row = $connection->fetchRow(
            $connection->select()
                ->from($this->resource->getTableName('url_rewrite'))
                ->where('request_path = ?', $requestPath)
                ->where('store_id = ?', $storeId)
        );

        return is_array($row) ? $row : null;
    }

    /**
     * The request path Magento generated for an entity in a store view (its current URL), when there is one.
     *
     * @param string $entityType
     * @param int $entityId
     * @param int $storeId
     * @return string|null
     */
    public function systemPath(string $entityType, int $entityId, int $storeId): ?string
    {
        $connection = $this->resource->getConnection();
        $path = $connection->fetchOne(
            $connection->select()
                ->from($this->resource->getTableName('url_rewrite'), ['request_path'])
                ->where('entity_type = ?', $entityType)
                ->where('entity_id = ?', $entityId)
                ->where('store_id = ?', $storeId)
                ->where('redirect_type = 0')
                ->where('is_autogenerated = 1')
                ->where('metadata IS NULL')
                ->order('url_rewrite_id ASC')
                ->limit(1)
        );

        return is_string($path) && $path !== '' ? $path : null;
    }

    /**
     * @param string $sku
     * @return int|null
     */
    public function productId(string $sku): ?int
    {
        if ($this->products === null) {
            $this->products = [];
            $this->skus = [];
            $connection = $this->resource->getConnection();
            $rows = $connection->fetchPairs(
                $connection->select()
                    ->from($this->resource->getTableName('catalog_product_entity'), ['entity_id', 'sku'])
            );
            foreach ($rows as $id => $productSku) {
                $this->products[mb_strtolower((string) $productSku)] = (int) $id;
                $this->skus[(int) $id] = (string) $productSku;
            }
        }

        return $this->products[mb_strtolower(trim($sku))] ?? null;
    }

    /**
     * @param int $id
     * @return string|null
     */
    public function sku(int $id): ?string
    {
        $this->productId('');

        return $this->skus[$id] ?? null;
    }

    /**
     * @param string $path a category path (Default Category/Men/Shirts)
     * @return int|null
     */
    public function categoryId(string $path): ?int
    {
        return $this->categories->id($path);
    }

    /**
     * @param int $id
     * @return string|null
     */
    public function categoryPath(int $id): ?string
    {
        return $this->categories->path($id);
    }

    /**
     * @param string $identifier
     * @param int $storeId
     * @return int|null
     */
    public function cmsPageId(string $identifier, int $storeId): ?int
    {
        $page = $this->cms->find(CmsRecords::PAGE, $identifier, [$storeId]);

        return $page === null ? null : (int) $page->getId();
    }

    /**
     * @param int $id
     * @return string|null
     */
    public function cmsPageIdentifier(int $id): ?string
    {
        $connection = $this->resource->getConnection();
        $identifier = $connection->fetchOne(
            $connection->select()
                ->from($this->resource->getTableName('cms_page'), ['identifier'])
                ->where('page_id = ?', $id)
        );

        return is_string($identifier) && $identifier !== '' ? $identifier : null;
    }

    /**
     * Creates or updates a rewrite.
     *
     * @param array<string, mixed>|null $existing the url_rewrite row to update, null for a new one
     * @param array<string, mixed> $data request_path, target_path, redirect_type, store_id, entity_type, entity_id,
     *        description, is_autogenerated, metadata
     * @return void
     */
    public function save(?array $existing, array $data): void
    {
        /** @var UrlRewrite $model */
        $model = $this->rewriteFactory->create();
        if ($existing !== null) {
            $this->rewriteResource->load($model, (int) $existing['url_rewrite_id']);
        }
        $model->addData($data);
        $this->rewriteResource->save($model);
    }

    /**
     * @param int $id
     * @return void
     */
    public function delete(int $id): void
    {
        /** @var UrlRewrite $model */
        $model = $this->rewriteFactory->create();
        $this->rewriteResource->load($model, $id);
        if ($model->getId()) {
            $this->rewriteResource->delete($model);
        }
    }

    /**
     * Every rewrite, as url_rewrite rows ordered by store and request path.
     *
     * @return \Generator<int, array<string, mixed>>
     */
    public function all(): \Generator
    {
        $connection = $this->resource->getConnection();
        $select = $connection->select()
            ->from($this->resource->getTableName('url_rewrite'))
            ->order(['store_id ASC', 'request_path ASC']);
        $statement = $connection->query($select);
        while (($row = $statement->fetch()) !== false) {
            yield $row;
        }
    }

    /**
     * @return int
     */
    public function count(): int
    {
        $connection = $this->resource->getConnection();

        return (int) $connection->fetchOne(
            $connection->select()->from($this->resource->getTableName('url_rewrite'), ['COUNT(*)'])
        );
    }
}
