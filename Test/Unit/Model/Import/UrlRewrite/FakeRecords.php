declare(strict_types=1);

namespace Iranimij\OpenImport\Test\Unit\Model\Import\UrlRewrite;

use Iranimij\OpenImport\Model\Import\UrlRewrite\UrlRewriteRecords;

/**
 * In-memory stand-in for the shop's rewrites and lookups.
 */
class FakeRecords extends UrlRewriteRecords
{
    /**
     * @var array<int, array<string, mixed>>
     */
    public array $saved = [];

    /**
     * @var int[]
     */
    public array $deleted = [];

    /**
     * @var array<string, array<string, mixed>>
     */
    private array $rewrites = [
        '1|shirt.html' => ['url_rewrite_id' => 3, 'request_path' => 'shirt.html', 'store_id' => 1, 'entity_type' => 'product',
            'entity_id' => 10, 'is_autogenerated' => 1, 'redirect_type' => 0, 'target_path' => 'catalog/product/view/id/10'],
        '1|sale' => ['url_rewrite_id' => 5, 'request_path' => 'sale', 'store_id' => 1, 'entity_type' => 'custom',
            'entity_id' => 0, 'is_autogenerated' => 0, 'redirect_type' => 0, 'target_path' => 'old'],
    ];

    // phpcs:ignore Magento2.CodeAnalysis.EmptyBlock
    public function __construct()
    {
    }

    public function storeCodes(): array
    {
        return ['default' => 1, 'de' => 2];
    }

    public function defaultStoreId(): int
    {
        return 1;
    }

    public function find(string $requestPath, int $storeId): ?array
    {
        return $this->rewrites[$storeId . '|' . $requestPath] ?? null;
    }

    public function systemPath(string $entityType, int $entityId, int $storeId): ?string
    {
        return $entityType === 'product' && $entityId === 10 && $storeId === 1 ? 'shirt.html' : null;
    }

    public function productId(string $sku): ?int
    {
        return strtolower($sku) === 'shirt' ? 10 : null;
    }

    public function sku(int $id): ?string
    {
        return $id === 10 ? 'SHIRT' : null;
    }

    public function categoryId(string $path): ?int
    {
        return $path === 'Default Category/Men' ? 20 : null;
    }

    public function categoryPath(int $id): ?string
    {
        return $id === 20 ? 'Default Category/Men' : null;
    }

    public function cmsPageId(string $identifier, int $storeId): ?int
    {
        return $identifier === 'about' ? 30 : null;
    }

    public function cmsPageIdentifier(int $id): ?string
    {
        return $id === 30 ? 'about' : null;
    }

    public function save(?array $existing, array $data): void
    {
        $data['existing_id'] = $existing['url_rewrite_id'] ?? null;
        $this->saved[] = $data;
    }

    public function delete(int $id): void
    {
        $this->deleted[] = $id;
    }
}
